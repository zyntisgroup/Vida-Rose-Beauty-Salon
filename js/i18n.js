class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('vida_rose_lang') || 'en';
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  bindEvents() {
    document.querySelectorAll('.js-lang-toggle').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        this.toggleLanguage();
      });
    });
  }

  toggleLanguage() {
    const newLang = this.currentLang === 'en' ? 'ar' : 'en';
    this.setLanguage(newLang);
  }

  setLanguage(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('vida_rose_lang', lang);
    this.applyLanguage(lang);

    // Dispatch event so animations and layout recalculate
    window.dispatchEvent(new CustomEvent('vidaRoseLanguageChanged', { detail: { lang } }));
  }

  applyLanguage(lang) {
    const dict = translations[lang];
    const isRtl = lang === 'ar';

    // Update HTML attributes
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    document.body.classList.toggle('is-rtl', isRtl);

    // Update text nodes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (dict[key].includes('\n')) {
          el.innerHTML = dict[key].replace(/\n/g, '<br>');
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Update language switch button text
    document.querySelectorAll('.js-lang-text').forEach(el => {
      el.textContent = dict['nav.lang_switch'];
    });
  }

  get(key) {
    return (translations[this.currentLang] && translations[this.currentLang][key]) || key;
  }
}

window.i18n = new I18nManager();
document.addEventListener('DOMContentLoaded', () => {
  window.i18n.init();
});
